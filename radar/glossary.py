_ASCII = re.compile(r"^[A-Za-z0-9+]+$")


def _pattern():
    # 긴 용어부터 — "현물 ETF" 가 "ETF" 보다 먼저 잡혀야 한다
    parts = []
    for term in sorted(GLOSSARY, key=len, reverse=True):
        esc = re.escape(term)
        if _ASCII.match(term):
            # 영문 용어는 앞뒤가 영문자면 안 된다(ETFs·Federal 등 오탐 방지). 숫자 뒤는 허용(25bp)
            parts.append(r"(?<![A-Za-z])%s(?![A-Za-z+])" % esc)
        else:
            parts.append(esc)
    return re.compile("|".join(parts))


_PAT = _pattern()


def annotate(text, used=None):
    """text 안의 어려운 단어에 풀이를 붙인다. used 에 이미 설명한 풀이가 쌓인다(메시지 단위로 공유)."""
    if not text:
        return text
    if used is None:
        used = set()
    out, pos = [], 0
    for m in _PAT.finditer(text):
        term = m.group(0)
        expl = GLOSSARY.get(term)
        end = m.end()
        out.append(text[pos:end])
        pos = end
        if not expl or expl in used:
            continue
        if text[end:end + 1] in ("(", "（"):  # 이미 괄호 설명이 붙어 있음
            used.add(expl)
            continue
        out.append("(%s)" % expl)
        used.add(expl)
    out.append(text[pos:])
    return "".join(out)
